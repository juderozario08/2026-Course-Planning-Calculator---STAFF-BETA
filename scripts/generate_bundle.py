#!/usr/bin/env python3
"""
Generates `data/curricula.bundle.js` by reading every `<Program>-<Year>.json`
file in `data/curricula/` and embedding them into a single JS file as the
global variable `embeddedCurricula`.

The bundle lets the planner work when `index.html` is opened directly
(file://), where browsers block fetch() of local JSON files.

Usage (from anywhere):
  python3 scripts/generate_bundle.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CURRICULA_DIR = os.path.join(ROOT, 'data', 'curricula')
BUNDLE_PATH = os.path.join(ROOT, 'data', 'curricula.bundle.js')

PATTERN = re.compile(r"^([A-Za-z]+)-([0-9]{4})\.json$")


def load_curricula():
    entries = {}
    for fn in sorted(os.listdir(CURRICULA_DIR)):
        m = PATTERN.match(fn)
        if not m:
            continue
        key = f"{m.group(1)}:{m.group(2)}"
        try:
            with open(os.path.join(CURRICULA_DIR, fn), 'r', encoding='utf-8') as f:
                entries[key] = json.load(f)
        except Exception as e:
            print('Skipping', fn, 'due to error:', e)
    return entries


def main():
    entries = load_curricula()

    out_lines = [
        '// This file is auto-generated by generate_bundle.py',
        'const embeddedCurricula = (function(){',
        '  const m = {};',
    ]
    for key, data in entries.items():
        # Escape closing script tags just in case
        json_text = json.dumps(data, indent=2).replace('</', '<\\/')
        out_lines.append(f'  m[{json.dumps(key)}] = {json_text};')
    out_lines.append('  return m;')
    out_lines.append('})();')

    with open(BUNDLE_PATH, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out_lines))

    print('Wrote', os.path.relpath(BUNDLE_PATH, ROOT), 'with', len(entries), 'entries')


if __name__ == '__main__':
    main()
